"""Build ../data.js for Hakoot Practice (v2, 27 Nov 2026).

    python3 tools/build.py

Only Pre-Final Sets now (Mew, 26 Nov late: longer, context-rich questions; no word ⇄ translation items).
- tools/prefinal.py  Sections I–II of every set (Units 1, 2, 4 · Company Profile · Describing Trends) and the
                     External Reading vocabulary-in-context items (ER_VOCAB)
- tools/content.py   only its two reading sets (er-read: main idea / details / pronouns, er-expr: expressions)
Section III (10 per set) = 4 reading + 3 expressions + 3 vocabulary-in-context, in article order.
Seeded, so the output only changes when the inputs change. Also stamps ?v= cache keys into index.html.
"""
import hashlib
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import content   # noqa: E402
import prefinal  # noqa: E402

QUOTA = {'u1': 14, 'u2': 14, 'u4': 15, 'cp': 7, 'dt': 10, 'er': 10}
ORDER = ['u1', 'u2', 'u4', 'cp', 'dt', 'er']
PARTS = [
    ('u1', 'Unit 1 · Career Choices', 'Section I · Unit 1'),
    ('u2', 'Unit 2 · Business Sectors', 'Section I · Unit 2'),
    ('u4', 'Unit 4 · Global Markets', 'Section I · Unit 4'),
    ('cp', 'Company Profile', 'Section II · Company Profile'),
    ('dt', 'Describing Trends', 'Section II · Describing Trends'),
    ('er', 'External Reading', 'Section III · External Reading'),
]
TREND_PARA = {'1': 3, '2': 5, '3': 7, '4': 9, '5': 11}


def para_key(q):
    """Article position of a reading question, so Section III runs through the article in order."""
    m = re.search(r'¶(\d+)', q)
    if m:
        return int(m.group(1))
    m = re.search(r'Trend (\d)', q)
    if m:
        return TREND_PARA[m.group(1)] - 0.5
    return 0  # whole article / main idea


def reading_items():
    by_id = {s['id']: s for s in content.SETS}
    read = [dict(q=q, a=a, ex=ex) for q, a, ex in by_id['er-read']['items']]
    expr = [dict(q=q, a=a, ex=ex) for q, a, ex in by_id['er-expr']['items']]
    vocab = [dict(q=q, a=a, ex=ex) for q, a, ex in prefinal.ER_VOCAB]
    n = len(prefinal.SETS)
    out = [[] for _ in range(n)]
    for pool, per in ((read, 4), (expr, 3), (vocab, 3)):
        pool = sorted(pool, key=lambda x: para_key(x['q']))
        picks = [[] for _ in range(n)]
        for i, it in enumerate(pool):          # spread the article across the sets
            if len(picks[i % n]) < per:
                picks[i % n].append(it)
        for k in range(n):
            assert len(picks[k]) == per, (per, len(pool))
            out[k] += picks[k]
    for k in range(n):
        out[k].sort(key=lambda x: para_key(x['q']))
        for it in out[k]:
            it.update(p='er', les='ER')
    return out


def check(q, where):
    a = q['a']
    assert len(a) == 4 and len(set(a)) == 4 and all(x.strip() for x in a), (where, q['q'])
    assert q['ex'].strip(), (where, q['q'])


def stamp():
    idx = os.path.join(ROOT, 'index.html')
    html = open(idx, encoding='utf-8').read()
    for name in ('data.js', 'app.js', 'style.css'):
        h = hashlib.sha1(open(os.path.join(ROOT, name), 'rb').read()).hexdigest()[:8]
        html = re.sub(re.escape(name) + r'\?v=[\w]+', f'{name}?v={h}', html)
    open(idx, 'w', encoding='utf-8').write(html)


def main():
    er = reading_items()
    exams = []
    seen = set()
    for k, items in enumerate(prefinal.SETS):
        qs = [x for p in ORDER[:-1] for x in items if x['p'] == p] + er[k]
        counts = {p: sum(1 for x in qs if x['p'] == p) for p in ORDER}
        assert counts == QUOTA, (k + 1, counts)
        for q in qs:
            check(q, f'set {k + 1}')
            key = (q.get('ctx', ''), q['q'], q.get('g'), tuple(q['a']))
            assert key not in seen, ('repeated question', q['q'])
            seen.add(key)
        exams.append({'id': f'pf{k + 1}', 'title': f'Pre-Final Set {k + 1}', 'qs': qs})
    data = {'parts': [{'id': p, 'en': en, 'sec': sec} for p, en, sec in PARTS], 'exams': exams}
    payload = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
    data['version'] = hashlib.sha1(payload.encode()).hexdigest()[:10]
    out = os.path.join(ROOT, 'data.js')
    with open(out, 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/build.py — edit tools/prefinal.py (or the reading sets in tools/content.py), then rebuild.\n')
        f.write('// a[0] is the right answer; the app shuffles the answers every time.\n')
        f.write('window.HP_DATA = ')
        json.dump(data, f, ensure_ascii=False, separators=(',', ':'))
        f.write(';\n')
    stamp()
    print(f'{len(exams)} Pre-Final Sets × 70 → {out} (version {data["version"]})')


if __name__ == '__main__':
    main()
